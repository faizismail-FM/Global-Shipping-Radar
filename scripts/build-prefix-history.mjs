// Rebuild src/data/prefixHistory.ts from a consol export saved as CSV.
// Usage: node scripts/build-prefix-history.mjs consol_list.csv
// Expects a header row with "Carrier" and "Container No(s)" columns (the
// standard consol list export). Only counts per owner prefix are written.
import fs from 'node:fs';

const [, , file] = process.argv;
if (!file) {
  console.error('usage: node scripts/build-prefix-history.mjs <consol-export.csv>');
  process.exit(1);
}
const MIN_SAMPLES = 30;

// Agent / carrier names as they appear in the export → CarrierSite id in src/lib/tracking/carrierLinks.ts.
const RULES = [
  ['WAN HAI', 'wan-hai'], ['ORIENT OVERSEAS', 'oocl'], ['INTERASIA', 'interasia'], ['RCL', 'rcl'], ['KMTC', 'kmtc'],
  ['OCEAN NETWORK', 'one'], ['EVERGREEN', 'evergreen'], ['COSCO', 'cosco'], ['COSCON', 'cosco'], ['YANG MING', 'yang-ming'],
  ['PIL ', 'pil'], ['CMA CGM', 'cma-cgm'], ['SINOKOR', 'sinokor'], ['HEUNG-A', 'sinokor'], ['HEUNG A', 'sinokor'], ['MAERSK', 'maersk'],
  ['MEDITERRANEAN SHIPPING', 'msc'], ['ANL', 'anl'], ['SITC', 'sitc'], ['TRANSWORLD', 'transworld'], ['MTT', 'mtt'],
  ['T.S. CONTAINER', 'ts-lines'], ['TS CONTAINER', 'ts-lines'], ['UNIFEEDER', 'unifeeder'], ['ECONSHIP', 'econship'],
  ['HAPAG', 'hapag-lloyd'], ['GOODRICH', 'goodrich'], ['EMIRATES', 'emirates'], ['SWIRE', 'swire'], ['HYUNDAI', 'hmm'], ['HMM', 'hmm'],
  ['ZIM', 'zim'], ['APL', 'apl'], ['ARKAS', 'arkas'],
];
const carrierId = (name) => {
  const u = name.toUpperCase();
  for (const [k, id] of RULES) if (u.includes(k)) return id;
  return null;
};

function parseCsv(text) {
  const rows = [];
  let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (q) {
      if (ch === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (ch === '"') q = false;
      else field += ch;
    } else if (ch === '"') q = true;
    else if (ch === ',') { row.push(field); field = ''; }
    else if (ch === '\n' || ch === '\r') { if (ch === '\r' && text[i + 1] === '\n') i++; row.push(field); rows.push(row); row = []; field = ''; }
    else field += ch;
  }
  if (field || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const rows = parseCsv(fs.readFileSync(file, 'utf8'));
const header = rows[0].map((h) => h.trim());
const ci = header.indexOf('Carrier');
const ni = header.findIndex((h) => /^Container No/i.test(h));
if (ci < 0 || ni < 0) { console.error('CSV needs "Carrier" and "Container No(s)" columns'); process.exit(1); }

const byPrefix = new Map();
let total = 0;
for (const r of rows.slice(1)) {
  if (!(r[ci] ?? '').trim()) continue; // no carrier recorded: nothing to learn
  const id = carrierId(r[ci] ?? '');
  for (const n of ((r[ni] ?? '').toUpperCase().match(/[A-Z]{4}\d{7}/g) ?? [])) {
    total++;
    const p = n.slice(0, 4);
    const entry = byPrefix.get(p) ?? { n: 0, counts: new Map() };
    entry.n++;
    if (id) entry.counts.set(id, (entry.counts.get(id) ?? 0) + 1);
    byPrefix.set(p, entry);
  }
}
const lines = [
  '/**',
  " * Which carrier a container prefix has actually travelled with in FM Global",
  " * Logistics' own bookings. Generated by scripts/build-prefix-history.mjs from a",
  ` * consol export (${total.toLocaleString('en-US')} containers, ${new Date().toLocaleString('en-US', { month: 'long', year: 'numeric' })}); contains only counts per`,
  ' * owner prefix, no shipment data.',
  ' *',
  ' * Used by the carrier link card to pre-select the likeliest carrier, which',
  ' * matters for leased boxes (Triton, Textainer, …) whose prefix says nothing',
  ' * about the carrier. Refresh with a newer export whenever the mix changes.',
  ' */',
  "import type { PrefixHistory } from '@/lib/tracking/carrierLinks';",
  '',
  'export const PREFIX_HISTORY: Readonly<Record<string, PrefixHistory>> = {',
];
let written = 0;
for (const [p, e] of [...byPrefix.entries()].sort()) {
  if (e.n < MIN_SAMPLES) continue;
  const top = [...e.counts.entries()].sort((a, b) => b[1] - a[1]).slice(0, 3);
  if (top.length === 0) continue;
  lines.push(`  ${p}: { samples: ${e.n}, carriers: [${top.map(([id, c]) => `{ carrier: '${id}', share: ${(c / e.n).toFixed(2).replace(/\.?0+$/, '') || '0'} }`).join(', ')}] },`);
  written++;
}
lines.push('};', '');
fs.writeFileSync(new URL('../src/data/prefixHistory.ts', import.meta.url), lines.join('\n'));
console.log(`${written} prefixes written from ${total} containers`);
